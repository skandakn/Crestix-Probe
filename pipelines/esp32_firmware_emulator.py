"""
Crestix Probe - ESP32 Microcontroller & In-Situ Sensor Firmware Emulator
========================================================================
Emulates hardware telemetry generated by an ESP32-WROOM-32 / ESP32-S3 microcontroller
interfaced with an HC-SR04 ultrasonic transducer and a 6-pin galvanic water level probe.

Simulates:
  - Ultrasonic acoustic echo travel time with ambient temperature noise
  - Contact resistance on galvanic probe pins immersed in conductive stormwater
  - CRC32 checksum computation for serial packet integrity
  - HTTP POST payload generation and periodic telemetry stream dispatch
"""

import time
import json
import zlib
import random
import math
import urllib.request
from typing import Dict, List, Tuple, Optional, Any


class VirtualESP32Probe:
    """Emulates a physical Crestix Probe hardware node."""

    def __init__(
        self,
        node_id: str = "river_sensor_alpha",
        mounting_height_cm: float = 28.63,
        temperature_mean_c: float = 25.5,
    ):
        self.node_id = node_id
        self.mounting_height = mounting_height_cm
        self.temp_mean = temperature_mean_c
        self.current_water_level_cm = 0.0

        # Pin heights from bottom of channel up (cm)
        self.pin_thresholds = [5.0, 10.0, 15.0, 20.0, 25.0, 28.0]
        self.packet_sequence = 0

    def set_true_water_level(self, level_cm: float):
        """Set environmental ground truth water level."""
        self.current_water_level_cm = max(0.0, min(self.mounting_height, level_cm))

    def read_galvanic_pins(self) -> List[int]:
        """Read 6 digital GPIO input pins."""
        pins = []
        for thresh in self.pin_thresholds:
            # Pin activates (1) when submerged
            is_wet = 1 if self.current_water_level_cm >= thresh else 0
            pins.append(is_wet)
        return pins

    def read_ultrasonic_distance(self) -> Tuple[float, float]:
        """
        Simulates HC-SR04 acoustic time-of-flight ranging:
          Air gap = mounting_height - water_level
        Returns: (raw_depth_cm, temperature_c)
        """
        temp_c = self.temp_mean + random.uniform(-0.5, 0.5)
        true_air_gap = self.mounting_height - self.current_water_level_cm

        # Add acoustic turbulence / surface ripple noise (+/- 0.4 cm)
        noise = random.gauss(0, 0.25)
        # 2% chance of multipath echo spike
        if random.random() < 0.02:
            noise += random.choice([-5.0, 8.0])

        measured_air_gap = max(2.0, true_air_gap + noise)
        measured_depth = max(0.0, self.mounting_height - measured_air_gap)

        return round(measured_depth, 2), round(temp_c, 1)

    def generate_telemetry_frame(self) -> Dict[str, Any]:
        """Generate full JSON packet matching bridge.py contract."""
        self.packet_sequence += 1
        depth_cm, temp_c = self.read_ultrasonic_distance()
        pins = self.read_galvanic_pins()

        payload = {
            "node_id": self.node_id,
            "packet_id": self.packet_sequence,
            "timestamp": time.time(),
            "depth_sonic": depth_cm,
            "probe_pins": pins,
            "temperature_c": temp_c,
            "battery_volts": round(3.7 + random.uniform(-0.05, 0.05), 2),
            "wifi_rssi_dbm": random.randint(-65, -55),
        }

        # Compute packet CRC32 checksum
        payload_bytes = json.dumps(payload, sort_keys=True).encode("utf-8")
        payload["crc32"] = hex(zlib.crc32(payload_bytes))

        return payload


