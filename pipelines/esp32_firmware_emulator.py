        frame = probe.generate_telemetry_frame()
        print(f"Set Ground Truth: {lvl:5.2f}cm -> Sonic Depth: {frame['depth_sonic']:5.2f}cm | "
              f"Pins: {frame['probe_pins']} | Temp: {frame['temperature_c']}C | CRC: {frame['crc32']}")

